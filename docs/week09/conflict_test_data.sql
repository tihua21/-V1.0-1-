-- =====================================================================
-- 第 10 周 · 九组冲突测试数据
-- 对应任务书表 2：以「已有 9:00—11:00」为基准，逐组造数据看结果。
--
-- 使用前提：
--   1. 已执行 docs/week07-08/schema.sql，库里已有 room 1=A101、room 2=B201、
--      user 1=admin、user 2=user1；
--   2. 后端按 README 启动，测试账号 user1 / 123456；
--   3. 本脚本可重复执行：先清理 2027-01-04 ~ 2027-01-12 的测试预约，
--      再重建测试用的自定义时段与基准预约。
--
-- 为什么需要自定义时段：
--   系统按方案 B 只允许选择 time_slot 预置时段，而表 2 的 9:00—11:00、
--   9:30—10:30、8:00—9:30、10:30—12:00、10:00—10:30 都不是已有的一小时时段，
--   所以脚本先插入这些"测试专用时段"，再通过接口选择它们提交，才能还原表 2。
--   这些时段名称统一以「冲突测试-」开头，方便清理，不要在生产数据里保留。
--
-- 九组数据分布在 9 个不同日期，避免上一组的成功预约影响下一组：
--   第 1 组 完全重叠           2027-01-04
--   第 2 组 前段重叠           2027-01-05
--   第 3 组 后段重叠           2027-01-06
--   第 4 组 新预约被包含       2027-01-07
--   第 5 组 新预约包含已有     2027-01-08
--   第 6 组 首尾相接（后）     2027-01-09
--   第 7 组 首尾相接（前）     2027-01-10
--   第 8 组 同日不同会议室     2027-01-11
--   第 9 组 取消后重订         2027-01-12
-- =====================================================================

USE meeting_room;

-- ---------------------------------------------------------------------
-- 0. 清理上一次执行留下的测试数据（可重复执行）
-- ---------------------------------------------------------------------
DELETE FROM booking_audit_log
 WHERE booking_id IN (
     SELECT id FROM booking
      WHERE booking_date BETWEEN '2027-01-04' AND '2027-01-12'
 );
DELETE FROM booking
 WHERE booking_date BETWEEN '2027-01-04' AND '2027-01-12';
DELETE FROM time_slot WHERE slot_name LIKE '冲突测试-%';

-- ---------------------------------------------------------------------
-- 1. 测试专用时段（名称前缀「冲突测试-」）
-- ---------------------------------------------------------------------
INSERT INTO time_slot (slot_name, start_time, end_time, duration_minutes, status) VALUES
    ('冲突测试-09:00-11:00', '09:00:00', '11:00:00', 120, 1),
    ('冲突测试-09:30-10:30', '09:30:00', '10:30:00',  60, 1),
    ('冲突测试-08:00-09:30', '08:00:00', '09:30:00',  90, 1),
    ('冲突测试-10:30-12:00', '10:30:00', '12:00:00',  90, 1),
    ('冲突测试-10:00-10:30', '10:00:00', '10:30:00',  30, 1);

-- ---------------------------------------------------------------------
-- 2. 每组基准预约（room 1 = A101，status=1 已预约，占时段）
--    首尾相接（前/后）用已有的 08:00-09:00 / 11:00-12:00 预置时段提交，
--    「同日不同会议室」的基准同样在 A101。
-- ---------------------------------------------------------------------
INSERT INTO booking
    (user_id, room_id, slot_id, booking_date, start_time, end_time, purpose, status, booking_no)
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-04', '2027-01-04 09:00:00', '2027-01-04 11:00:00', '第1组-完全重叠-基准', 1, 'BKTEST-01'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-05', '2027-01-05 09:00:00', '2027-01-05 11:00:00', '第2组-前段重叠-基准', 1, 'BKTEST-02'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-06', '2027-01-06 09:00:00', '2027-01-06 11:00:00', '第3组-后段重叠-基准', 1, 'BKTEST-03'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-10:00-10:30'),
       '2027-01-07', '2027-01-07 10:00:00', '2027-01-07 10:30:00', '第4组-新预约被包含-基准', 1, 'BKTEST-04'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-08', '2027-01-08 09:00:00', '2027-01-08 11:00:00', '第5组-新预约包含已有-基准', 1, 'BKTEST-05'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-09', '2027-01-09 09:00:00', '2027-01-09 11:00:00', '第6组-首尾相接后-基准', 1, 'BKTEST-06'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-10', '2027-01-10 09:00:00', '2027-01-10 11:00:00', '第7组-首尾相接前-基准', 1, 'BKTEST-07'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-11', '2027-01-11 09:00:00', '2027-01-11 11:00:00', '第8组-同日不同会议室-基准', 1, 'BKTEST-08'
UNION ALL
SELECT 2, 1, (SELECT id FROM time_slot WHERE slot_name = '冲突测试-09:00-11:00'),
       '2027-01-12', '2027-01-12 09:00:00', '2027-01-12 11:00:00', '第9组-取消后重订-基准', 1, 'BKTEST-09';

